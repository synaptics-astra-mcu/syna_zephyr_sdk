/*
 * Advertised format capabilities returned by get_caps().
 * Must stay in sync with ov02c10_modes[].
 * 1920x1080 is RAW10 only; RAW8 (SBGGR8) is available at 480x270 and
 * 640x480 only. set_fmt() validates requests against this table first.
 *
 * WARNING: Each entry in ov02c10_fmts must have a corresponding entry in
 * ov02c10_modes with matching width, height, and pixelformat. Mismatches
 * cause format validation to accept formats that cannot be programmed.
 * When adding new modes, update both arrays to avoid drift.
 */
static const struct video_format_cap ov02c10_fmts[] = {
	OV02C10_VIDEO_FORMAT_CAP(480, 270, VIDEO_PIX_FMT_SBGGR8),
	OV02C10_VIDEO_FORMAT_CAP(640, 480, VIDEO_PIX_FMT_SBGGR8),
	OV02C10_VIDEO_FORMAT_CAP(1920, 1080, VIDEO_PIX_FMT_SBGGR10P),
	OV02C10_VIDEO_FORMAT_CAP(480, 270, VIDEO_PIX_FMT_SBGGR10P),
	OV02C10_VIDEO_FORMAT_CAP(640, 480, VIDEO_PIX_FMT_SBGGR10P),
	{0},
};

/*
 * Build-time check: sync caps and modes entry counts. This is a
 * size-only guard; it does not validate semantic pairing across tables.
 */
_Static_assert(ARRAY_SIZE(ov02c10_fmts) - 1 == ARRAY_SIZE(ov02c10_modes),
		"ov02c10_fmts and ov02c10_modes entry count mismatch");

static inline const struct ov02c10_mode_config *
ov02c10_find_mode(const struct video_format *fmt)
{
	uint8_t i;

	for (i = 0; i < ARRAY_SIZE(ov02c10_modes); i++) {
		if (fmt->width == ov02c10_modes[i].width &&
		    fmt->height == ov02c10_modes[i].height &&
		    fmt->pixelformat == ov02c10_modes[i].pixelformat) {
			return &ov02c10_modes[i];
		}
	}
	return NULL;
}

static const struct ov02c10_mode_config *
ov02c10_find_nearest_mode_by_frmival(const struct video_format *fmt,
					const struct video_frmival *frmival)
{
	const struct ov02c10_mode_config *selected_mode = NULL;
	uint64_t best_error = UINT64_MAX;
	uint8_t i;

	/*
	 * Each supported format maps to a single FPS entry in ov02c10_modes[].
	 * Keep nearest-match selection for correct behavior if frame-rate
	 * variants are added later. One discrete frame interval per format.
	 */

	for (i = 0; i < ARRAY_SIZE(ov02c10_modes); i++) {
		uint64_t requested_frames;
		uint64_t candidate_error;

		if (ov02c10_modes[i].width != fmt->width ||
		    ov02c10_modes[i].height != fmt->height ||
		    ov02c10_modes[i].pixelformat != fmt->pixelformat) {
			continue;
		}

		if (ov02c10_modes[i].fps == 0U) {
			continue;
		}

	requested_frames = (uint64_t)frmival->numerator * ov02c10_modes[i].fps;
	candidate_error = (requested_frames > frmival->denominator) ?
				(requested_frames - frmival->denominator) :
				(frmival->denominator - requested_frames);

		if (selected_mode == NULL || candidate_error < best_error) {
			selected_mode = &ov02c10_modes[i];
			best_error = candidate_error;
		}
	}

	return selected_mode;
}

static int ov02c10_set_frmival(const struct device *dev,
			       struct video_frmival *frmival)
{
	struct ov02c10_data *drv_data = dev->data;
	const struct ov02c10_config *cfg = dev->config;
	const struct ov02c10_mode_config *selected_mode;
	int ret = 0;

	if (!drv_data->initialized) {
		return -ENODEV;
	}

	if (drv_data->streaming) {
		return -EBUSY;
	}

	if (drv_data->cur_mode == NULL) {
		return -ENODEV;
	}

	if (frmival->numerator == 0U || frmival->denominator == 0U) {
		return -EINVAL;
	}

	selected_mode = ov02c10_find_nearest_mode_by_frmival(
		&drv_data->fmt, frmival);

	if (selected_mode == NULL) {
		return -ENOTSUP;
	}

	if (drv_data->cur_mode != selected_mode) {
		ret = video_write_cci_multiregs16(&cfg->i2c,
			selected_mode->regs, selected_mode->num_regs);
		if (ret < 0) {
			LOG_ERR("Unable to apply OV02C10 mode %ux%u",
				selected_mode->width,
				selected_mode->height);
			return ret;
		}

		drv_data->cur_mode = selected_mode;
	}

	drv_data->ctrls.pixel_rate.val64 = selected_mode->pixel_rate;
	frmival->numerator = 1U;
	frmival->denominator = selected_mode->fps;
	return ret;
}

static int ov02c10_set_fmt(const struct device *dev,
			   struct video_format *fmt)
{
	struct ov02c10_data *drv_data = dev->data;
	const struct ov02c10_config *cfg = dev->config;
	const struct ov02c10_mode_config *mode;
	struct video_frmival def_frmival;
	size_t caps_idx;
	int ret = 0;

	if (!drv_data->initialized) {
		ret = -ENODEV;
		return ret;
	}

	/* Validate against the advertised caps table */
	ret = video_format_caps_index(ov02c10_fmts, fmt, &caps_idx);
	if (ret < 0) {
		LOG_ERR("Unsupported format %s %ux%u",
			VIDEO_FOURCC_TO_STR(fmt->pixelformat),
			fmt->width, fmt->height);
		ret = -ENOTSUP;
		return ret;
	}

	mode = ov02c10_find_mode(fmt);
	if (mode == NULL) {
		LOG_ERR("No mode config for format %s %ux%u",
			VIDEO_FOURCC_TO_STR(fmt->pixelformat),
			fmt->width, fmt->height);
		ret = -EINVAL;
		return ret;
	}

	if (drv_data->cur_mode == mode &&
	    drv_data->fmt.width == fmt->width &&
	    drv_data->fmt.height == fmt->height &&
	    drv_data->fmt.pixelformat == fmt->pixelformat &&
	    drv_data->fmt.type == fmt->type) {
		return 0;
	}

	ret = video_write_cci_multiregs16(&cfg->i2c, mode->regs,
		mode->num_regs);
	if (ret < 0) {
		LOG_ERR("Unable to apply OV02C10 mode %ux%u", mode->width,
			mode->height);
		return ret;
	}

	drv_data->cur_mode = mode;
	drv_data->fmt = *fmt;

	if (mode->bits_per_pixel == 0U) {
		LOG_ERR("Invalid bits_per_pixel for %s %ux%u",
			VIDEO_FOURCC_TO_STR(fmt->pixelformat),
			fmt->width, fmt->height);
		ret = -EINVAL;
		return ret;
	}

	drv_data->ctrls.pixel_rate.val64 = mode->pixel_rate;

	def_frmival.numerator = 1U;
	def_frmival.denominator = mode->fps;
	ret = ov02c10_set_frmival(dev, &def_frmival);
	if (ret < 0) {
		LOG_ERR("Unable to set OV02C10 frame interval for %ux%u",
			mode->width, mode->height);
	}

	return ret;
}

static int ov02c10_get_fmt(const struct device *dev,
			   struct video_format *fmt)
{
	struct ov02c10_data *drv_data = dev->data;

	*fmt = drv_data->fmt;

	return 0;
}

static int ov02c10_get_caps(const struct device *dev,
			    struct video_caps *caps)
{
	ARG_UNUSED(dev);

	/* Validate buffer type - sensor source only supports OUTPUT buffers */
	if (caps->type != VIDEO_BUF_TYPE_OUTPUT) {
		LOG_ERR("Unsupported buffer type: %u (expected OUTPUT)",
			caps->type);
		return -ENOTSUP;
	}

	caps->format_caps = ov02c10_fmts;
	caps->min_vbuf_count = 0;
	return 0;
}

static int ov02c10_set_stream(const struct device *dev,
			      bool enable,
			      enum video_buf_type type)
{
	const struct ov02c10_config *cfg = dev->config;
	struct ov02c10_data *drv_data = dev->data;
	int ret = 0;

	/* Validate buffer type - sensor source only supports OUTPUT buffers */
	if (type != VIDEO_BUF_TYPE_OUTPUT) {
		LOG_ERR("Unsupported buffer type: %u (expected OUTPUT)",
			type);
		return -ENOTSUP;
	}

	if (!drv_data->initialized) {
		return -ENODEV;
	}

	if (drv_data->streaming == enable) {
		return 0;
	}

	ret = video_write_cci_reg(&cfg->i2c, OV02C10_REG8(SYS_CTRL0_REG),
				 enable ? SYS_CTRL0_START : SYS_CTRL0_STBY);
	if (ret != 0) {
		return ret;
	}

	drv_data->streaming = enable;
	return ret;
}

static int ov02c10_get_frmival(const struct device *dev,
			       struct video_frmival *frmival)
{
	struct ov02c10_data *drv_data = dev->data;

	if (!drv_data->initialized) {
		return -ENODEV;
	}

	if (drv_data->cur_mode == NULL) {
		return -EIO;
	}

	frmival->numerator = 1;
	frmival->denominator = drv_data->cur_mode->fps;

	return 0;
}

static int ov02c10_enum_frmival(const struct device *dev,
				struct video_frmival_enum *fie)
{
	uint32_t match_index = 0U;
	uint8_t i;

	ARG_UNUSED(dev);

	if (fie->format == NULL) {
		return -EINVAL;
	}

	for (i = 0; i < ARRAY_SIZE(ov02c10_modes); i++) {
		if (ov02c10_modes[i].width != fie->format->width ||
		    ov02c10_modes[i].height != fie->format->height ||
		    ov02c10_modes[i].pixelformat != fie->format->pixelformat) {
			continue;
		}

		if (match_index != fie->index) {
			match_index++;
			continue;
		}

		fie->type = VIDEO_FRMIVAL_TYPE_DISCRETE;
		fie->discrete.numerator = 1;
		fie->discrete.denominator = ov02c10_modes[i].fps;

		return 0;
	}

	return -ENOTSUP;
}


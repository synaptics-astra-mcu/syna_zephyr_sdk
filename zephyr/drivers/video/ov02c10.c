static int ov02c10_init_controls(const struct device *dev)
{
	struct ov02c10_data *drv_data = dev->data;
	uint64_t min_rate = UINT64_MAX;
	uint64_t max_rate = 0;
	uint8_t i;
	int ret;

	for (i = 0; i < ARRAY_SIZE(ov02c10_modes); i++) {
		if (ov02c10_modes[i].pixel_rate < min_rate) {
			min_rate = ov02c10_modes[i].pixel_rate;
		}

		if (ov02c10_modes[i].pixel_rate > max_rate) {
			max_rate = ov02c10_modes[i].pixel_rate;
		}
	}

	ret = video_init_ctrl(
		&drv_data->ctrls.pixel_rate, dev, VIDEO_CID_PIXEL_RATE,
		(struct video_ctrl_range){
			.min64 = min_rate,
			.max64 = max_rate,
			.step64 = 1,
			.def64 = ov02c10_modes[0].pixel_rate,
		});

	return ret;
}

static int ov02c10_init(const struct device *dev)
{
	const struct ov02c10_config *cfg = dev->config;
	struct ov02c10_data *drv_data = dev->data;
	struct video_format fmt = {
		.type = VIDEO_BUF_TYPE_OUTPUT,
		.pixelformat = ov02c10_modes[0].pixelformat,
		.width = ov02c10_modes[0].width,
		.height = ov02c10_modes[0].height,
	};
	uint32_t chip_id = 0;
	int ret;

	drv_data->initialized = false;
	drv_data->streaming = false;

	if (!device_is_ready(cfg->i2c.bus)) {
		LOG_ERR("Bus device is not ready");
		return -ENODEV;
	}

	ret = ov02c10_apply_board_config(dev);
	if (ret < 0) {
		return ret;
	}

	/* Small guard delay between GPIO/MCLK enable and first I2C access. */
	k_sleep(K_MSEC(OV02C10_DELAY_GPIO_CONFIG_TO_DEASSERT_MS));

	ret = video_write_cci_reg(&cfg->i2c, OV02C10_REG8(SW_RESET_REG), 0x01);
	if (ret < 0) {
		LOG_ERR("Unable to perform software reset");
		return ret;
	}
	LOG_DBG("Software reset issued");

	ret = video_read_cci_reg(&cfg->i2c, OV02C10_REG16(CHIP_ID_REG),
		&chip_id);
	if (ret < 0) {
		LOG_ERR("Unable to read sensor chip ID, ret = %d", ret);
		return ret;
	}

	if (chip_id != CHIP_ID) {
		LOG_DBG("Unexpected OV02C10 chip ID: 0x%04x expected 0x%04x",
			chip_id, CHIP_ID);
		return -ENODEV;
	}
	LOG_DBG("OV02C10 chip ID verified: 0x%04x", chip_id);

	/* Validate bus type - driver only supports CSI-2 D-PHY */
	if (cfg->bus_type != VIDEO_BUS_TYPE_CSI2_DPHY) {
		LOG_ERR("Unsupported bus type: %u. expected CSI-2 D-PHY.",
			cfg->bus_type);
		return -ENOTSUP;
	}


	ret = ov02c10_init_controls(dev);
	if (ret < 0) {
		LOG_ERR("Unable to initialize controls");
		return ret;
	}
	LOG_DBG("Controls initialized");

	drv_data->initialized = true;

	ret = ov02c10_set_fmt(dev, &fmt);
	if (ret < 0) {
		LOG_ERR("Unable to configure default OV02C10 mode");
		drv_data->initialized = false;
		return ret;
	}
	LOG_DBG("Default format configured: %ux%u pixelformat=0x%08x",
		fmt.width, fmt.height, fmt.pixelformat);

	LOG_DBG("OV02C10 sensor initialized successfully");
	return 0;
}

static int ov02c10_apply_board_config(const struct device *dev)
{
	const struct ov02c10_config *cfg = dev->config;
	int ret;

	if (cfg->pcfg != NULL) {
		ret = pinctrl_apply_state(cfg->pcfg, PINCTRL_STATE_DEFAULT);
		if (ret != 0) {
			LOG_ERR("Failed to apply pinctrl default state: %d",
				ret);
			return ret;
		}
		LOG_INF("pinctrl default state applied");
	}

#if DT_ANY_INST_HAS_PROP_STATUS_OKAY(powerdown_gpios)
	if (cfg->powerdown_gpio.port != NULL) {
		if (!gpio_is_ready_dt(&cfg->powerdown_gpio)) {
			LOG_ERR("Power down GPIO device not ready");
			return -ENODEV;
		}

		ret = gpio_pin_configure_dt(&cfg->powerdown_gpio,
			GPIO_OUTPUT_ACTIVE);
		if (ret < 0) {
			LOG_ERR("Unable to configure power down GPIO: %d", ret);
			return ret;
		}
		LOG_INF("Power down GPIO active: %s pin %u",
			cfg->powerdown_gpio.port->name,
			cfg->powerdown_gpio.pin);
	}
#endif

#if DT_ANY_INST_HAS_PROP_STATUS_OKAY(shutdown_gpios)
	if (cfg->shutdown_gpio.port != NULL) {
		if (!gpio_is_ready_dt(&cfg->shutdown_gpio)) {
			LOG_ERR("Shutdown GPIO device not ready");
			return -ENODEV;
		}

		ret = gpio_pin_configure_dt(&cfg->shutdown_gpio,
			GPIO_OUTPUT_ACTIVE);
		if (ret < 0) {
			LOG_ERR("Unable to configure shutdown GPIO: %d", ret);
			return ret;
		}
		LOG_INF("Shutdown GPIO active: %s pin %u",
			cfg->shutdown_gpio.port->name, cfg->shutdown_gpio.pin);
	}
#endif

#if DT_ANY_INST_HAS_PROP_STATUS_OKAY(mclk_control_reg) && \
			DT_ANY_INST_HAS_PROP_STATUS_OKAY(mclk_control_val)
	if (cfg->power_up_delay_ms != 0U) {
		k_msleep(cfg->power_up_delay_ms);
	}

	if (cfg->mclk_control_reg != 0U) {
		uint32_t val;

		sys_write32(cfg->mclk_control_val, cfg->mclk_control_reg);
		val = sys_read32(cfg->mclk_control_reg);
		LOG_INF("MCLK ctrl: wrote 0x%08x to 0x%08x, read back 0x%08x",
			cfg->mclk_control_val, cfg->mclk_control_reg, val);
	}

	if (cfg->mclk_settle_delay_ms != 0U) {
		k_msleep(cfg->mclk_settle_delay_ms);
	}
#endif
	return 0;
}

